use crate::{
    cpu::Cpu,
    ram::{Address, Ram},
};

mod cpu;
mod instruction;
mod ram;
mod register;

fn main() {
    let mut ram = Ram::new();

    let mem = [
        0x91u8, 0x01, 0x16, 0x81, 0x00, 0x01, 0x04, 0x00, 0xF8, 0x15, 0xD0, 0x00, 0x91, 0x02, 0x01,
        0x00, 0x01, 0x01, 0x02, 0xF0, 0x03, 0xE0, 0x48, 0x65, 0x6C, 0x6C, 0x6F, 0x2C, 0x20, 0x77,
        0x6F, 0x72, 0x6C, 0x64, 0x21, 0x0A, 0x00,
    ];
    for (i, byte) in mem.iter().enumerate() {
        ram.set(i as Address, *byte as i8);
    }

    let mut cpu = Cpu::new(&mut ram);

    cpu.cycle();
}
